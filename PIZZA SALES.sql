-- a. Classic → Regular  
--b. Veggie → Vegetarian  
--c. Chicken → Non-Vegetarian  
--d. Supreme → Special 

ALTER TABLE PIZZA_SALES ADD PIZZA_TYPE TEXT;

UPDATE PIZZA_SALES 
SET PIZZA_TYPE=
CASE PIZZA_CATEGORY
WHEN 'Classic' THEN 'Regular'
WHEN 'VEGGIE' THEN 'Vegetarian'
WHEN 'CHICKEN' THEN 'Non-Vegetarian'
WHEN 'SUPREME' THEN 'Special'
END;

