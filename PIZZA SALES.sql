 SELECT PIZZA_NAME,PIZZA_CATEGORY,TOTAL_PRICE FROM( SELECT PIZZA_NAME,PIZZA_CATEGORY,TOTAL_PRICE, RANK() OVER(PARTITION BY PIZZA_CATEGORY ORDER BY TOTAL_PRICE DESC) AS RANK_NUMBER FROM PIZZA_SALES) AS RANKED WHERE RANK_NUMBER=1;

 --12. Find the top 2 highest-priced pizzas from each pizza category. 
 SELECT PIZZA_NAME,PIZZA_CATEGORY,TOTAL_PRICE FROM( SELECT PIZZA_NAME,PIZZA_CATEGORY,TOTAL_PRICE, RANK() OVER(PARTITION BY PIZZA_CATEGORY ORDER BY TOTAL_PRICE DESC) AS RANK_NUMBER FROM PIZZA_SALES) AS RANKED WHERE RANK_NUMBER<=2;

