SELECT PIZZA_NAME,TOTAL_PRICE, RANK() OVER(ORDER BY TOTAL_PRICE DESC) AS RANK_NUMBER  FROM PIZZA_SALES;

--9. Assign a dense rank to all pizzas based on total price from highest to lowest. 
